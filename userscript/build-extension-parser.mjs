// Share the proven parser without shipping the legacy userscript's network/UI code.
//
//   node userscript/build-extension-parser.mjs          write extension/amount-parser.js
//   node userscript/build-extension-parser.mjs --check  fail if the committed file is stale
import {readFileSync, writeFileSync} from 'node:fs';

// A Windows checkout can materialise the userscript with CRLF, and the end
// marker below spans a line break, so extraction failed there. Normalise first
// (from #9 by @Z-Han-Z).
const read = url => readFileSync(url, 'utf8').replace(/\r\n/g, '\n');
const source = read(new URL('./fx-pulse-hover.user.js', import.meta.url));
const start = source.indexOf('  const CURRENCIES =');
const end = source.indexOf('  /* ==========================================================================\n   * B.');
if (start < 0 || end <= start) throw new Error('Parser source markers missing');
const output = '/* Generated by userscript/build-extension-parser.mjs. Do not edit directly. */\n(() => {\n"use strict";\n' + source.slice(start, end) + '\nglobalThis.FXAmountParser = {parseAll, parseText, parseNumber, convertAmount, formatMoney, resolveCurrency, markerCensus, profileOf, buildProfile, MARKERS, CURRENCIES};\n})();\n';
const target = new URL('../extension/amount-parser.js', import.meta.url);

if (process.argv.includes('--check')) {
  if (read(target) !== output) {
    console.error('extension/amount-parser.js is stale; run: node userscript/build-extension-parser.mjs');
    process.exit(1);
  }
  console.log('amount-parser.js matches the userscript parser');
} else {
  writeFileSync(target, output);
  console.log('wrote extension/amount-parser.js');
}
